"""Compile the current RU/EN dictionaries into display-only AS tables."""
from pathlib import Path
import hashlib,io,json,sys,zipfile
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
from localization89 import strings

def main():
    lookup=strings()
    # Displayed titles and headings are uppercased by the Beta skin.
    lookup.update({k.upper():v.upper() for k,v in list(lookup.items())})
    reverse={v:k for k,v in lookup.items()}
    catalog=json.loads((ROOT/'data/beta924/normalized/catalog.json').read_text('utf8'))
    from ws_codegen import localized_plain_text
    ru,en=catalog['localization']['ru_ru'],catalog['localization']['en_us']
    for key,value in en.items():
        if key in ru:
            for source,target in ((value,ru[key]),(localized_plain_text(value),localized_plain_text(ru[key]))):
                reverse[source]=target;reverse[source.upper()]=target.upper()
    chunks=[];methods=[]
    for label,table in [('load',lookup),('reverse',reverse)]:
        names=[];rows=list(sorted(table.items()))
        for start in range(0,len(rows),100):
            name=label+str(start//100);names.append(name)
            methods.append('private static function '+name+'(o:Object):void{\n'+''.join('o['+json.dumps(k,ensure_ascii=False)+']='+json.dumps(v,ensure_ascii=False)+';\n' for k,v in rows[start:start+100])+'}\n')
        chunks.append('public static function '+label+'():Object{var o:Object={};'+''.join(n+'(o);' for n in names)+'return o;}\n')
    target=ROOT/'BetaGwent/ui/src/BetaGwentTextData.as'
    target.write_text('// Generated by build_text_language136.py; never translate dictionary keys.\npackage { public class BetaGwentTextData {\n'+''.join(chunks+methods)+'}}\n','utf8')
    raw=json.dumps(strings(),ensure_ascii=False).encode();buffer=io.BytesIO()
    with zipfile.ZipFile(buffer,'w',zipfile.ZIP_DEFLATED) as archive:archive.writestr('ru-en.json',raw)
    files=list((ROOT/'BetaGwent/build/release060-preparation/languages').glob('*/original-beta.json'));all_text=io.BytesIO()
    with zipfile.ZipFile(all_text,'w',zipfile.ZIP_DEFLATED) as archive:
        for file in files:archive.writestr(file.parent.name+'.json',file.read_bytes())
    report=dict(entries=len(strings()),ruEnRawBytes=len(raw),ruEnZipBytes=len(buffer.getvalue()),
        originalLanguages=len(files),allOriginalRawBytes=sum(p.stat().st_size for p in files),allOriginalZipBytes=len(all_text.getvalue()),
        newLanguagesEnabled=False,fontsForNewLanguagesIncluded=False,
        sources={p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in ['data/beta924/design/english89.json','BetaGwent/ui/src/BetaGwentTextData.as','tools/ui/build_text_language136.py']})
    (ROOT/'docs/evidence/text-language136.json').write_text(json.dumps(report,indent=2)+'\n','utf8')
    print('RU/EN display tables ready; compressed text dictionary:',len(buffer.getvalue()),'bytes')

if __name__=='__main__':main()
