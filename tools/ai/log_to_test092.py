"""Turn one AI decision from scriptslog.txt into a regression test.

Needs a build that writes AI_POSITION (0.9.2 decks2 and later). Each AI decision then logs
the full position; this tool rebuilds it in the JS harness and writes tools/ai/<name>.js:

  python -X utf8 tools/ai/log_to_test092.py "C:\\Users\\...\\The Witcher 3\\scriptslog.txt" --match -1 --decision 16 --name check_log_cantarella
  python -X utf8 tools/ai/log_to_test092.py LOG --list            # matches and decisions with the logged choice

By default the test asserts that the AI now chooses differently from the logged (wrong) move;
--expect-same asserts the identical choice (useful to pin a good move). Edit the generated
check() lines to state the exact expectation, then add the name to tools/ai/validate091.py.
"""
from pathlib import Path
import argparse, json, re, sys
ROOT=Path(__file__).resolve().parents[2]

def matches(lines):
    out=[];cur=None
    for line in lines:
        m=re.search(r'AI_POSITION schema=1 decision=(\d+) (.*)',line)
        if m:
            d=int(m.group(1))
            if d==1 and (cur is None or 1 in cur): cur={};out.append(cur)
            if cur is None: cur={};out.append(cur)
            if d not in cur:
                head=dict(re.findall(r'(\w+)=(\S*)',m.group(2)));cur[d]=dict(head=head,cards=[],select=None,parts=set())
            continue
        m=re.search(r'AI_POSITION_CARDS decision=(\d+) part=(\d+)(.*)',line)
        if m and cur is not None:
            e=cur.get(int(m.group(1)))
            if e is not None and int(m.group(2)) not in e['parts']:
                e['parts'].add(int(m.group(2)));e['cards']+=m.group(3).split()
            continue
        m=re.search(r'AI_REASON schema=1 decision=(\d+) event=(SELECT|PASS) (.*)',line)
        if m and cur is not None:
            e=cur.get(int(m.group(1)))
            if e is not None and e['select'] is None: e['select']=m.group(2)+' '+m.group(3)
    return out

def card_tuple(text):
    keys=['id','template','side','owner','zone','index','power','base','armor','tokens','timer','tier','playable']
    return dict(zip(keys,map(int,text.split(':'))))

def generate(entry,name,expect_same):
    h=entry['head'];cards=[card_tuple(c) for c in entry['cards']]
    assert len(cards)==int(h['cardCount']),f"incomplete position: {len(cards)} of {h['cardCount']} cards logged"
    crowns=[int(x) for x in h['crowns'].split(',')];passed=[x=='1' for x in h['passed'].split(',')]
    leaders=[x=='1' for x in h['leaders'].split(',')];weather=[int(x) for x in h['weather'].strip(',').split(',') if x!='']
    known=[int(x) for x in h.get('known','').split(',') if x]
    sel=entry['select'] or ''
    tm=re.search(r'template=(\d+)',sel);logged_template=int(tm.group(1)) if tm and sel.startswith('SELECT') else 0
    logged_kind='pass' if sel.startswith('PASS') else ('leader' if 'action=leader' in sel else 'card')
    payload=dict(head=h,cards=cards,crowns=crowns,passed=passed,leaders=leaders,weather=weather,known=known,
                 logged=dict(kind=logged_kind,template=logged_template,text=sel[:240]))
    js=r'''// Generated by tools/ai/log_to_test092.py from a scriptslog AI decision. Edit the expectation.
'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm');
const snapshot=path.resolve(process.argv[2]),context=vm.createContext({console});
const fixture=fs.readFileSync(path.join(__dirname,'check_consume_self.js'),'utf8').split('Host.strength=4;')[1].split('// Alone:')[0];
const P=PAYLOAD;
context.P=P;
vm.runInContext(['runtime.js','rules.js','harness.js'].map(f=>fs.readFileSync(path.join(snapshot,f),'utf8')).join('\n')+'\nHost.strength=4;'+fixture+String.raw`
const strength=Number(P.head.strength);Host.strength=strength;Host.matchStrength=[strength,strength];
const g=new CBetaGwentDuelSession();if(!g.InitializeWithPresets(Number(P.head.presetOne),Number(P.head.presetTwo)))throw Error('initialize');
g.mulligan=false;g.pendingCard=null;g.pendingLeader=null;g.waiting=false;g.recordVisuals=false;
const leaders=[g.Leader(1),g.Leader(2)];
for(const c of g.live.slice())if(c!==leaders[0]&&c!==leaders[1])c.Move(c.Snapshot().positionPlayerId,512,0);
for(let i=0;i<2;i++)if(leaders[i]&&!P.leaders[i])leaders[i].Move(i+1,512,0);
const leaderTemplates=new Set(leaders.filter(Boolean).map(c=>c.TemplateId()));
for(const c of P.cards){
 if(c.zone===512||leaderTemplates.has(c.template)&&c.zone!==1&&c.zone!==2&&c.zone!==4)continue;
 const card=add(g,c.template,c.zone,c.index,c.side,c.power);
 card.cardState.ownerId=c.owner;card.cardState.tokenMask=c.tokens;card.cardState.timerValue=c.timer;
 if(c.armor)card.power.SetCurrentPair(c.power,c.armor);
}
g.match.roundNumber=Number(P.head.round);g.match.playerOne.crowns=P.crowns[0];g.match.playerTwo.crowns=P.crowns[1];
g.match.playerOne.hasPassed=P.passed[0];g.match.playerTwo.hasPassed=P.passed[1];
g.match.currentPlayerId=2;g.match.roundActive=true;g.match.turnActive=true;
g.aiStartingDeckOne.Clear();for(const t of P.known)g.aiStartingDeckOne.PushBack(t);
if(P.weather.some(x=>x))console.log('NOTE: weather tokens in the log are not rebuilt:',P.weather.join(','));
const logs=[];Host.log=s=>logs.push(s);let ok;try{ok=g.OpponentStep();}finally{Host.log=null;}
check(ok&&!g.IsFatal(),'rebuilt decision completes');
const line=logs.find(s=>/event=(SELECT|PASS) /.test(s))||'';
const kind=line.includes('event=PASS')?'pass':(line.includes('action=leader')?'leader':'card');
const tm=/template=(\d+)/.exec(line),template=kind==='card'&&tm?Number(tm[1]):0;
console.log('LOGGED:',P.logged.text);console.log('NOW:   ',line.replace('AI_REASON schema=1 ','').slice(0,240));
const same=kind===P.logged.kind&&template===P.logged.template;
EXPECTATION
globalThis.report={checks,logged:P.logged,now:{kind,template,line},actualWitcherScript:true,nativeGameTested:false};
`,context,{filename:'NAME.bundle.js',timeout:180000});
if(process.argv[3])fs.writeFileSync(process.argv[3],JSON.stringify(context.report,null,2)+'\n');
'''
    expectation=("check(same,'the AI repeats the logged choice');" if expect_same else
                 "check(!same,'the AI no longer repeats the logged choice ('+P.logged.kind+' '+P.logged.template+')');")
    return js.replace('PAYLOAD',json.dumps(payload,ensure_ascii=False)).replace('EXPECTATION',expectation).replace('NAME',name)

def main():
    p=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('log',type=Path);p.add_argument('--match',type=int,default=-1,help='1-based match number, negative counts from the end')
    p.add_argument('--decision',type=int);p.add_argument('--name');p.add_argument('--expect-same',action='store_true')
    p.add_argument('--list',action='store_true');p.add_argument('--out-dir',type=Path,default=ROOT/'tools/ai')
    a=p.parse_args()
    ms=matches(a.log.read_text('utf8',errors='replace').splitlines())
    if not ms:raise SystemExit('No AI_POSITION lines: play with a build that logs positions (0.9.2 decks2 or later).')
    if a.list:
        for i,m in enumerate(ms,1):
            print(f'match {i}:');[print(f'  decision {d}: {e["select"] or "?"}'[:170]) for d,e in sorted(m.items())]
        return
    m=ms[a.match-1 if a.match>0 else a.match]
    if a.decision not in m:raise SystemExit(f'decision {a.decision} not in that match; use --list')
    name=a.name or f'check_log_d{a.decision}'
    if not re.fullmatch(r'check_[a-z0-9_]+',name):raise SystemExit('--name must look like check_something')
    out=a.out_dir/(name+'.js')
    if out.exists():raise SystemExit(f'{out} exists; choose another --name')
    out.write_text(generate(m[a.decision],name,a.expect_same),'utf8');print('wrote',out)
    print('run: node',out.relative_to(ROOT) if out.is_relative_to(ROOT) else out,'<snapshot>   then add',name,'to tools/ai/validate091.py')

if __name__=='__main__':main()
