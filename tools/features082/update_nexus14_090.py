SAVES = {'en': '## Saves and compatibility', 'ru': '## Сохранения и совместимость'}


def fix(t, lang=None):
    if ITEMS not in t:
        t = t.replace(ASSETS, ASSETS + ' + ' + ITEMS)
    if KEEP_NEW not in t:
        t = t.replace(KEEP_OLD, KEEP_NEW)
        if lang:
            old, new = FOLDER[lang]
            lines = t.split('\n')
            for i, line in enumerate(lines):
                if KEEP_NEW in line and 'After-Uninstall' in line:
                    assert old in line, (lang, line[:120]); lines[i] = line.replace(old, new, 1)
            t = '\n'.join(lines)
    return t


def edit(p, lang=None):
    t, bom, crlf = u.load(p); n = fix(t, lang)
    if n != t: u.store(p, n, bom, crlf); print('updated', p.relative_to(ROOT))
    return n


def main():
    for lang in FOLDER:
        edit(NEXUS / lang / 'manual.md', lang)
    for lang in ['en', 'ru']:
        edit(ROOT / f'docs/releases/0.9.0_CLEANUP_{lang.upper()}.md', lang)
        for name in ['post.md', 'post.bbcode.txt']:
            edit(NEXUS / lang / name)
        p = NEXUS / lang / 'changelog.md'; t = edit(p, lang); _, bom, crlf = u.load(p)
        if LINE[lang] not in t:
            t = u.insert_after_list(t, t.split('\n').index(SAVES[lang]), LINE[lang]); u.store(p, t, bom, crlf)
            print('changelog', lang)
        bb = NEXUS / lang / 'changelog.bbcode.txt'; b0, bbom, bcrlf = u.load(bb)
        if to_bbcode(t) != b0: u.store(bb, to_bbcode(t), bbom, bcrlf)
    for name in ['POST_0.9.0_EN_RU.md', 'NEXUS_POST_0.9.0_EN_RU.bbcode.txt']:
        edit(NEXUS / name)
    # Combined description/preview files are regenerated by refresh_showcase090.py.


if __name__ == '__main__':
    main()
