"""Per-card keyword phrases for all 13 Beta locales, from the original Beta tooltips.

Beta marks keywords as <keyword=...>Text</keyword> in Localization/<locale>.csv inside
StreamingAssets/data_definitions. Variables are substituted exactly as in
tools/languages137/prepare_card_text.py, so each phrase occurs verbatim in the shown text.
Writes BetaGwentKeywords090.as (ActionScript data + colouring) to the given folder.
"""
from pathlib import Path
import csv, io, json, re, sys, zipfile, hashlib
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
from ws_codegen import localized_plain_text
SOURCE = ROOT / 'Gwent 0.9.24.3.432/Gwent_Data/StreamingAssets/data_definitions'
LOCALES = ['ru_ru', 'en_us', 'de_de', 'fr_fr', 'it_it', 'pl_pl', 'es_es', 'es_mx', 'pt_br', 'jp_jp', 'kr_kr', 'zh_cn', 'zh_tw']
COLOR = '0xE8A94A'  # Beta keyword gold (reference screenshots, ability text)


def tables():
    with zipfile.ZipFile(SOURCE) as archive:
        for locale in LOCALES:
            raw = archive.read(f'Localization/{locale}.csv')
            rows = csv.DictReader(io.StringIO(raw.decode('utf-8-sig'), newline=''), delimiter=';')
            yield locale, {r['Key']: r.get(locale, '') or '' for r in rows if r.get('Key')}


def variables(catalog, table):
    result = {}
    for g in catalog['abilities']:
        if g['type'] != 'CardAbility':
            continue
        values = result.setdefault(g['templateId'], {})
        for group in g['sourceTree']['children']:
            if group['tag'] not in ('TemporaryVariables', 'PersistentVariables'):
                continue
            for v in group['children']:
                a = v['attributes']
                if a.get('Type') == 'IntVar':
                    values[a['Name']] = a['V']
                elif a.get('Type') == 'CardDefVar':
                    templates = [x['attributes']['TemplateId'] for x in v['children'] if 'TemplateId' in x['attributes']]
                    if templates:
                        values[a['Name']] = table.get(templates[0] + '_name', templates[0])
    return result


def main():
    out = Path(sys.argv[1])
    catalog = json.loads((ROOT / 'data/beta924/normalized/catalog.json').read_bytes())
    data = []; counts = {}
    for locale, table in tables():
        values = variables(catalog, table); cards = {}
        for t in catalog['templates']:
            ident = t['templateId']
            value = table.get(str(ident) + '_tooltip', '')
            for key, replacement in values.get(ident, {}).items():
                value = re.sub(r'\{\s*' + re.escape(key) + r'\s*\}', lambda m, r=str(replacement): r, value, flags=re.I)
            phrases = []
            for phrase in re.findall(r'<keyword=[^>]*>(.*?)</keyword>', value, flags=re.S):
                plain = localized_plain_text(phrase).strip()
                if plain and plain not in phrases:
                    phrases.append(plain)
            if phrases:
                cards[str(ident)] = sorted(phrases, key=len, reverse=True)
        data.append(cards); counts[locale] = len(cards)
    body = json.dumps([None] + data, ensure_ascii=False, separators=(',', ':'))
    source = '''﻿package {
    import flash.text.TextField;
    import flash.text.TextFormat;
    // Generated by tools/features082/build_keywords090.py from the original Beta
    // data_definitions (sha256 %s). Keyword phrases per locale (1..13) and card.
    public class BetaGwentKeywords090 {
        public static const COLOR:uint=%s;
        private static const DATA:Array=%s;
        public static function apply(field:TextField,id:int,language:int):void
        {
            if(!field||id<=0||language<1||language>13||!DATA[language])return;
            var list:Array=DATA[language][String(id)];if(!list)return;
            var text:String=field.text;var marked:Array=[];
            for each(var phrase:String in list){
                var at:int=text.indexOf(phrase);
                while(at>=0){
                    var free:Boolean=true;
                    for each(var range:Array in marked)if(at<range[1]&&at+phrase.length>range[0]){free=false;break;}
                    if(free){var format:TextFormat=new TextFormat();format.color=COLOR;field.setTextFormat(format,at,at+phrase.length);marked.push([at,at+phrase.length]);}
                    at=text.indexOf(phrase,at+phrase.length);
                }
            }
        }
    }
}
''' % (hashlib.sha256(SOURCE.read_bytes()).hexdigest(), COLOR, body)
    out.mkdir(parents=True, exist_ok=True)
    (out / 'BetaGwentKeywords090.as').write_bytes(source.replace('\r\n', '\n').replace('\n', '\r\n').encode('utf8'))
    print(json.dumps(dict(bytes=len(source.encode('utf8')), cards=counts)))


if __name__ == '__main__':
    main()
