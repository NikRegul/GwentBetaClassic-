"""0.9.6: full UI dictionary for strings that had only Russian or the English
fallback of BetaGwentUiText142. Source tables: tools/languages137/ui096/t*.py
(ru -> en, de, fr, it, pl, es, pt, jp, kr, zh_cn, zh_tw; es_mx = es).
Checks every glyph against the frozen locale resource charset (text138) and
writes BetaGwentUiText096.as into the five UI source copies."""
from pathlib import Path
import json, re, runpy, sys
ROOT = Path(__file__).resolve().parents[2]
ORDER = ['en_us', 'de_de', 'fr_fr', 'it_it', 'pl_pl', 'es_es', 'pt_br', 'jp_jp', 'kr_kr', 'zh_cn', 'zh_tw']
CODES = ['', 'ru_ru', 'en_us', 'de_de', 'fr_fr', 'it_it', 'pl_pl', 'es_es', 'es_mx', 'pt_br', 'jp_jp', 'kr_kr', 'zh_cn', 'zh_tw']
def charset(code):
    s = (ROOT / 'BetaGwent/build-inputs/authoring/text138' / code / 'BetaLocale137.as').read_text('utf8')
    return set(json.loads(re.search(r'public var characters:String=("(?:[^"\\]|\\.)*")', s)[1]))
def main():
    table = {}
    for f in sorted((ROOT / 'tools/languages137/ui096').glob('t*.py')): table.update(runpy.run_path(str(f))['T'])
    out = {code: {} for code in CODES[2:]}
    problems = []
    for ru, values in table.items():
        assert len(values) == 11, ru
        per = dict(zip(ORDER, values)); per['es_mx'] = per['es_es']
        for code in CODES[2:]: out[code][ru] = per[code]
    for code in CODES[2:]:
        chars = charset(code)
        for ru, v in out[code].items():
            bad = sorted(set(c for c in v + v.upper() if c not in chars and c not in '\n'))
            if bad: problems.append((code, ru, ''.join(bad)))
    if problems:
        for p in problems: print('missing glyphs', *p)
        sys.exit(1)
    rows = [json.dumps([out[c] for c in CODES[2:]], ensure_ascii=False, separators=(',', ':'))]
    text = '''package {
    // GENERATED by tools/languages137/build_ui_text096.py. Complete UI strings for
    // the 12 non-Russian text languages; applied after BetaGwentUiText142 so the
    // former English fallback becomes the real translation.
    public class BetaGwentUiText096 {
        private static const BY:Array=%s;
        public static function extend(value:int,data:Object):Object {
            if(value<2||value>13)return data;
            var map:Object=BY[value-2];
            for(var key:String in map){data[key]=map[key];data[key.toUpperCase()]=String(map[key]).toUpperCase();}
            return data;
        }
    }
}
''' % rows[0]
    raw = b'\\xef\\xbb\\xbf'.decode('unicode_escape').encode('latin1') + text.replace('\n', '\r\n').encode('utf8')
    for folder in ['src', 'src-BetaGwentBoard', 'src-GwintGame', 'src-DeckBuilder', 'src-BetaGwentKeg']:
        (ROOT / 'BetaGwent/ui' / folder / 'BetaGwentUiText096.as').write_bytes(raw)
    print(json.dumps(dict(strings=len(table), languages=12)))
if __name__ == '__main__': main()
